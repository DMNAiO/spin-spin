            and schemaname = 'public'
            and tablename = 'profiles'
    ) then
        execute 'alter publication supabase_realtime add table public.profiles';
    end if;

    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
            and schemaname = 'public'
            and tablename = 'group_rules'
    ) then
        execute 'alter publication supabase_realtime add table public.group_rules';
    end if;
end;
$$;


-- Retensi chat: pesan dihapus setelah berumur tiga bulan.
-- Aktifkan extension pg_cron jika project belum memilikinya.
create extension if not exists pg_cron;


do $$
declare
    existing_job_id bigint;
begin
    select jobid
    into existing_job_id
    from cron.job
    where jobname = 'delete-old-chat-messages'
    limit 1;

    if existing_job_id is not null then
        perform cron.unschedule(existing_job_id);
    end if;

    perform cron.schedule(
        'delete-old-chat-messages',
        '0 3 * * *',
        $job$
            delete from public.messages
            where created_at < now() - interval '3 months';

            delete from public.conversations
            where not exists (
                select 1
                from public.messages
                where messages.conversation_id = conversations.id
            );
        $job$
    );
end;
$$;
